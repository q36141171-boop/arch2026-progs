"""Build the target's small reverse-search tables with a host-side BFS."""

from array import array
from collections import deque
from itertools import permutations, product
from pathlib import Path


SOURCES = (
    (1, 4, 2, 0, 3, 5, 6),
    (0, 1, 2, 4, 5, 6, 3),
    (0, 2, 5, 3, 1, 4, 6),
)
TWISTS = (
    (1, 2, 0, 2, 1, 0, 0),
    (0, 0, 0, 1, 2, 1, 2),
    (0, 0, 0, 0, 0, 0, 0),
)
INVERSE = (2, 1, 0, 5, 4, 3, 8, 7, 6)
PERMUTATIONS = 5040
ORIENTATIONS = 729


def quarter_turns():
    perms = list(permutations(range(7)))
    perm_rank = {p: rank for rank, p in enumerate(perms)}
    turns_p = [tuple(perm_rank[tuple(p[i] for i in row)] for row in SOURCES)
               for p in perms]

    prefixes = list(product(range(3), repeat=6))
    orient_rank = {o: rank for rank, o in enumerate(prefixes)}
    turns_o = []
    for prefix in prefixes:
        o = prefix + (-sum(prefix) % 3,)
        turns_o.append(tuple(orient_rank[tuple((o[i] + t) % 3
                                              for i, t in zip(row, twist))[:6]]
                             for row, twist in zip(SOURCES, TWISTS)))
    return turns_p, turns_o


def all_turns(quarters):
    rows = []
    for state in range(len(quarters)):
        moves = []
        for face in range(3):
            next_state = state
            for _ in range(3):
                next_state = quarters[next_state][face]
                moves.append(next_state)
        rows.append(tuple(moves))
    return rows


def coordinate_distances(turns):
    distances = [255] * len(turns)
    distances[0] = 0
    pending = deque([0])
    while pending:
        state = pending.popleft()
        for neighbor in turns[state]:
            if distances[neighbor] == 255:
                distances[neighbor] = distances[state] + 1
                pending.append(neighbor)
    assert 255 not in distances
    return distances


def reverse_tables(turns_p, turns_o):
    # The full distance array and BFS frontiers exist only on the host.
    size = PERMUTATIONS * ORIENTATIONS
    seen = bytearray(size)
    seen[0] = 1
    frontier = array("I", [0])
    near = [15]  # Solved state has distance zero and no first move.
    diameter = []
    visited = 1
    for distance in range(1, 12):
        next_frontier = array("I")
        for state in frontier:
            p, o = divmod(state, ORIENTATIONS)
            for move, (next_p, next_o) in enumerate(zip(turns_p[p], turns_o[o])):
                index = next_p * ORIENTATIONS + next_o
                if seen[index]:
                    continue
                seen[index] = 1
                next_frontier.append(index)
                key = (next_p << 10) | next_o
                if distance <= 5:
                    near.append((key << 7) | (distance << 4) | INVERSE[move])
                if distance == 11:
                    diameter.append((key << 7) | INVERSE[move])
        visited += len(next_frontier)
        print(f"distance {distance}: {len(next_frontier)}")
        frontier = next_frontier
    assert visited == size
    assert len(near) == 12224 and len(diameter) == 2644
    return sorted(near), sorted(diameter)


def write_tables(tables, target):
    with (
        (target / "rubik_tables.h").open("w", encoding="ascii", newline="\n") as c,
        (target / "rubik_tables.inc").open("w", encoding="ascii", newline="\n") as asm,
    ):
        c.write("/* Generated by mytests/generate_rubik_tables.py. */\n"
                "// clang-format off\n")
        asm.write("# Generated by mytests/generate_rubik_tables.py.\n"
                  "    .section .rodata\n")
        for name, c_type, directive, alignment, numbers in tables:
            if c_type:
                c.write(f"static const {c_type} {name}[{len(numbers)}] = {{\n")
            asm.write(f"    .balign {alignment}\n.L{name}:\n")
            for start in range(0, len(numbers), 8):
                values = ", ".join(str(n) for n in numbers[start:start + 8])
                if c_type:
                    c.write(f"    {values},\n")
                asm.write(f"    {directive} {values}\n")
            if c_type:
                c.write("};\n\n")
            asm.write(f"    .equ .L{name}_count, {len(numbers)}\n\n")
        c.write("// clang-format on\n")


def main():
    quarter_p, quarter_o = quarter_turns()
    turns_p, turns_o = all_turns(quarter_p), all_turns(quarter_o)
    near, diameter = reverse_tables(turns_p, turns_o)
    # Each assembly lookup can binary search only the matching permutation.
    offsets = [0] * (PERMUTATIONS + 1)
    for entry in near:
        offsets[(entry >> 17) + 1] += 1
    for i in range(1, len(offsets)):
        offsets[i] += offsets[i - 1]
    tables = (
        ("next_p", "uint16_t", ".half", 2, [v for row in quarter_p for v in row]),
        ("next_o", "uint16_t", ".half", 2, [v for row in quarter_o for v in row]),
        ("distance_p", "uint8_t", ".byte", 1, coordinate_distances(turns_p)),
        ("distance_o", "uint8_t", ".byte", 1, coordinate_distances(turns_o)),
        ("near", "uint32_t", ".word", 4, near),
        ("diameter", "uint32_t", ".word", 4, diameter),
        ("near_offsets", None, ".half", 2, offsets),
    )
    target = Path(__file__).resolve().parents[1] / "src" / "rubik"
    write_tables(tables, target)


if __name__ == "__main__":
    main()
